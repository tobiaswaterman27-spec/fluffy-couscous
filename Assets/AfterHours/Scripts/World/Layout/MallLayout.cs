        public static Vector3 WingForward(WingId w)
        {
            switch (w)
            {
                case WingId.North: return Vector3.forward;
                case WingId.East: return Vector3.right;
                case WingId.South: return Vector3.back;
                default: return Vector3.left;
            }
        }

        /// <summary>Right-hand side when standing in the wing facing outwards.</summary>
        public static Vector3 WingRight(WingId w) => Vector3.Cross(Vector3.up, WingForward(w));

        public static Vector3 WingPoint(WingId w, float u, float v, float y)
        {
            return WingForward(w) * u + WingRight(w) * v + Vector3.up * y;
        }

        public static AreaRect WingRect(WingId w, float u0, float u1, float v0, float v1)
        {
            Vector3 a = WingPoint(w, u0, v0, 0f);
            Vector3 b = WingPoint(w, u1, v1, 0f);
            return new AreaRect(a.x, a.z, b.x, b.z);
        }

        public static float WingFacingYaw(WingId w)
        {
            switch (w)
            {
                case WingId.North: return 0f;
                case WingId.East: return 90f;
                case WingId.South: return 180f;
                default: return 270f;
            }
        }

        /// <summary>Which quadrant (sx, sz) lies on the given side of a wing.</summary>
        public static (int sx, int sz) QuadrantBeside(WingId w, int side)
        {
            Vector3 p = WingForward(w) * 30f + WingRight(w) * 30f * side;
            return (p.x > 0 ? 1 : -1, p.z > 0 ? 1 : -1);
        }

        public static float AnchorEndFor(MallFloor f, WingId w)
        {
            return f == MallFloor.Ground && w == WingId.South ? EntranceHallEnd : AnchorEnd;
        }

        public static AreaRect CoreRect(int sx, int sz) => CoreLocal.Mirrored(sx, sz);

        public static IEnumerable<AreaRect> LiftShafts()
        {
            yield return PublicLiftA;
            yield return PublicLiftB;
            yield return ServiceLift;
