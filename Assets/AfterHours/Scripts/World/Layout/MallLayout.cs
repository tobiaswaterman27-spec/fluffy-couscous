    /// <summary>
    /// THE fixed master plan of the mall. Everything that needs to know where things are reads this:
    /// the 3D builder, the physical directory board, developer teleports and review cameras, and later
    /// Elliot's AI zones and the escape-route puzzles. It is generated by fixed rules (no randomness),
    /// so the mall is identical on every run and on every player's machine.
    ///
    /// Overall shape: a cross. A central 3-storey atrium (with a 20 x 20 m open void, fountain, info desk,
    /// directory, clock, escalators, lifts and a bridge), four shopping wings (North/East/South/West, 80 m long,
    /// 12 m concourse, shops both sides, staff service corridors behind the shops), an anchor store at the end
    /// of every wing on every floor, back-of-house blocks between the wings (stairwells, plant, offices,
    /// toilets, loading), one enormous single-level car park underneath, and a roof.
    ///
    /// Coordinates: metres. +Z = North, +X = East. Ground floor top surface is y = 0.
    /// Within a wing: u = distance outwards from the mall centre, v = sideways (+ = right when facing outwards).
    /// </summary>
    public static class MallLayout
