    /// <summary>Axis-aligned rectangle on the ground plane (X/Z), in metres.</summary>
    [Serializable]
    public struct AreaRect
    {
        public float minX, minZ, maxX, maxZ;

        public AreaRect(float x0, float z0, float x1, float z1)
        {
            minX = Mathf.Min(x0, x1);
            maxX = Mathf.Max(x0, x1);
            minZ = Mathf.Min(z0, z1);
            maxZ = Mathf.Max(z0, z1);
        }

        public float Width => maxX - minX;
        public float Depth => maxZ - minZ;
        public Vector2 Center => new Vector2((minX + maxX) * 0.5f, (minZ + maxZ) * 0.5f);
        public bool Contains(float x, float z) => x >= minX && x <= maxX && z >= minZ && z <= maxZ;
        public bool Overlaps(AreaRect o) => minX < o.maxX && maxX > o.minX && minZ < o.maxZ && maxZ > o.minZ;
        public AreaRect Expanded(float m) => new AreaRect(minX - m, minZ - m, maxX + m, maxZ + m);

        /// <summary>Same rectangle mirrored into the quadrant given by the signs.</summary>
        public AreaRect Mirrored(int sx, int sz) => new AreaRect(minX * sx, minZ * sz, maxX * sx, maxZ * sz);
    }

