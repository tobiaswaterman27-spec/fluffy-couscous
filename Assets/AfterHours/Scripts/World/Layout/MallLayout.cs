        /// <summary>The walkable footprint of a shop floor (G, 1, 2) as non-overlapping rectangles.</summary>
        public static List<AreaRect> FloorRegions(MallFloor f)
        {
            var r = new List<AreaRect>
            {
                new AreaRect(-AtriumHalf, -AtriumHalf, AtriumHalf, AtriumHalf),
                new AreaRect(-OuterWall, WingStart, OuterWall, WingEnd),     // North wing
                new AreaRect(-OuterWall, -WingEnd, OuterWall, -WingStart),   // South wing
                new AreaRect(WingStart, -WingStart, WingEnd, WingStart),     // East wing core
                new AreaRect(OuterWall, WingStart, WingEnd, OuterWall),
                new AreaRect(OuterWall, -OuterWall, WingEnd, -WingStart),
                new AreaRect(-WingEnd, -WingStart, -WingStart, WingStart),   // West wing core
                new AreaRect(-WingEnd, WingStart, -OuterWall, OuterWall),
                new AreaRect(-WingEnd, -OuterWall, -OuterWall, -WingStart),
            };
            foreach (var (sx, sz) in Quadrants)
            {
                r.Add(new AreaRect(OuterWall, OuterWall, QuadrantOuter, QuadrantOuter).Mirrored(sx, sz));
            }
            r.Add(new AreaRect(-OuterWall, WingEnd, OuterWall, AnchorEnd));      // North anchor
            r.Add(new AreaRect(WingEnd, -OuterWall, AnchorEnd, OuterWall));      // East anchor
            r.Add(new AreaRect(-AnchorEnd, -OuterWall, -WingEnd, OuterWall));    // West anchor
            float southEnd = AnchorEndFor(f, WingId.South);
            r.Add(new AreaRect(-OuterWall, -southEnd, OuterWall, -WingEnd));      // South anchor / entrance hall
            return r;
        }

        /// <summary>Openings through a floor plate (atrium void, lift shafts, stairwells, store stair).</summary>
        public static List<AreaRect> FloorHoles(MallFloor f)
        {
            var h = new List<AreaRect>();
            if (f == MallFloor.Level1 || f == MallFloor.Level2) h.Add(new AreaRect(-VoidHalf, -VoidHalf, VoidHalf, VoidHalf));
            if (f == MallFloor.Roof) return h;
            foreach (AreaRect lift in LiftShafts()) h.Add(lift);
            foreach (var (sx, sz) in Quadrants) h.Add(CoreRect(sx, sz));
            if (f == MallFloor.Level1) h.Add(DepartmentStairHole);
            return h;
        }

