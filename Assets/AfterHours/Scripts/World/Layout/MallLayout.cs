        static readonly float[] WidthPattern = { 10f, 8f, 12f, 8f, 6f, 10f, 9f, 7f, 11f, 8f };

        static void GenerateShops()
        {
            foreach (MallFloor f in ShopFloors)
            {
                foreach (WingId w in Wings)
                {
                    for (int side = -1; side <= 1; side += 2)
                    {
                        var (qx, qz) = QuadrantBeside(w, side);
                        bool toiletsHere = QuadrantRoomA(f, qx, qz).type == FacilityType.Toilets
                                           && (w == WingId.East || w == WingId.West);
                        float staffStart = side > 0 ? 58f : 74f;

                        float cursor = WingStart;
                        int index = 1;
                        int pattern = Hash((int)f, (int)w, side, 7) % WidthPattern.Length;
                        bool toiletsDone = !toiletsHere, staffDone = false;
                        while (cursor < WingEnd - 0.01f)
                        {
                            if (!toiletsDone && cursor >= 26f)
                            {
                                passages.Add(new Passage { floor = f, wing = w, side = side, u0 = cursor, u1 = cursor + 3f, isPublic = true });
                                cursor += 3f;
                                toiletsDone = true;
                                continue;
                            }
                            if (!staffDone && cursor >= staffStart)
                            {
                                passages.Add(new Passage { floor = f, wing = w, side = side, u0 = cursor, u1 = cursor + 3f, isPublic = false });
                                cursor += 3f;
                                staffDone = true;
                                continue;
                            }

                            float width = WidthPattern[pattern % WidthPattern.Length];
                            pattern++;
                            if (WingEnd - (cursor + width) < 5f) width = WingEnd - cursor;
                            AddShop(f, w, side, index++, cursor, cursor + width);
                            cursor += width;
                        }
                    }
                }
            }
        }

        static void AddShop(MallFloor f, WingId w, int side, int index, float u0, float u1)
        {
            int h = Hash((int)f + 11, (int)w + 3, side + 5, index);
            var unit = new MallUnit
            {
                code = $"{FloorCode(f)}-{w.ToString()[0]}{(side > 0 ? "R" : "L")}{index:00}",
                floor = f,
                wing = w,
                side = side,
                u0 = u0,
                u1 = u1,
                rect = WingRect(w, u0, u1, ConcourseHalf * side, ShopBack * side)
            };

            // Roughly 1 in 9 units is vacant ("TO LET"), typical of a slightly neglected centre.
            if (h % 9 == 4)
            {
                unit.category = UnitCategory.Vacant;
                unit.name = "TO LET";
                unit.access = UnitAccess.Shuttered;
                unit.style = FurnishStyle.None;
            }
            else
            {
                (string name, UnitCategory cat) pick = PickShop(f, h);
                unit.name = pick.name;
                unit.category = pick.cat;
                int a = (h / 7) % 10;
                unit.access = a <= 1 ? UnitAccess.OpenShutter
                            : a == 2 ? UnitAccess.ShutterJammed
                            : a <= 4 ? UnitAccess.LockedGlass
                            : a == 5 ? UnitAccess.BrokenLock
                            : UnitAccess.Shuttered;
                unit.style = StyleFor(unit.category);
            }
            units.Add(unit);
        }

