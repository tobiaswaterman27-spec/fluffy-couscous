        static void GenerateAnchors()
        {
            foreach (MallFloor f in ShopFloors)
            {
                foreach (WingId w in Wings)
                {
                    AnchorSpec a = Anchor(f, w);
                    float end = AnchorEndFor(f, w);
                    float v0 = -OuterWall, v1 = OuterWall;
                    // Ground West: the fire-exit corridor runs through the middle; the store is the north half.
                    if (f == MallFloor.Ground && w == WingId.West) v0 = 2f;
                    units.Add(new MallUnit
                    {
                        code = $"{FloorCode(f)}-{w.ToString()[0]}A",
                        name = a.name,
                        category = a.cat,
                        floor = f,
                        wing = w,
                        side = 0,
                        u0 = WingEnd,
                        u1 = end,
                        rect = WingRect(w, WingEnd, end, v0, v1),
                        access = a.access,
                        style = a.style,
                        isAnchor = true
                    });
                }
            }
        }

